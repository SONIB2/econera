// Concatenates supabase/migrations/*.sql in order into one file for the Supabase SQL editor of a NEW, empty project.
// Usage: node scripts/bundle-migrations.mjs  → supabase/staging/all-migrations.sql
import { readdir, readFile, writeFile } from "node:fs/promises";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();
let out = `-- ECONERA: every migration in order (${files.length} files), generated by scripts/bundle-migrations.mjs.\n-- Run ONCE on an empty staging project. Never on production: production already has 0001-0020.\nbegin;\n`;
for (const f of files) out += `\n-- =====================================================================\n-- ${f}\n-- =====================================================================\n${await readFile(new URL(f, dir), "utf8")}\n`;
out += "\ncommit;\n";
await writeFile(new URL("../supabase/staging/all-migrations.sql", import.meta.url), out);
console.log(`Wrote supabase/staging/all-migrations.sql from ${files.length} migrations: ${files.join(", ")}`);
