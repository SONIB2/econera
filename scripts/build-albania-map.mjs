// Generates lib/albania-map.ts from Natural Earth data (world-atlas, public domain). Run: node scripts/build-albania-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-10m.json", import.meta.url)));
const albania = feature(topo, topo.objects.countries).features.find((f) => f.id === "008");
const bbox = { west: 19.2, east: 21.15, south: 39.55, north: 42.72 };
const k = Math.cos(((bbox.north + bbox.south) / 2) * (Math.PI / 180));
const width = 400;
const scale = width / ((bbox.east - bbox.west) * k);
const height = Math.round((bbox.north - bbox.south) * scale);
const project = ([lng, lat]) => [((lng - bbox.west) * k * scale).toFixed(1), ((bbox.north - lat) * scale).toFixed(1)];
const polygons = albania.geometry.type === "Polygon" ? [albania.geometry.coordinates] : albania.geometry.coordinates;
const d = polygons.map((poly) => poly.map((ring) => "M" + ring.map((c) => project(c).join(",")).join("L") + "Z").join("")).join("");
writeFileSync(new URL("../lib/albania-map.ts", import.meta.url), `// Generated by scripts/build-albania-map.mjs from Natural Earth 1:10m (public domain) via world-atlas.
export const ALBANIA = { width: ${width}, height: ${height}, path: ${JSON.stringify(d)} } as const;
const BBOX = ${JSON.stringify(bbox)};
const K = ${k};
const SCALE = ${scale};
export function project(lng: number, lat: number): [number, number] {
  return [(lng - BBOX.west) * K * SCALE, (BBOX.north - lat) * SCALE];
}
`);
console.log("height", height, "path length", d.length);
